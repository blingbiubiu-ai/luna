import { beforeEach, afterEach, test, expect } from "bun:test";
import { Hono } from "hono";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { eq } from "drizzle-orm";
import { DataConnection } from "../../src/data";
import * as schema from "../../src/data/schema";
import { setLunaHome } from "../../src/shared";
import { SessionStore } from "../../src/sessions/session-store";
import { createSessionCommandAdminRoutes } from "../../src/server/routes/session-commands";
import { fixtureScope } from "../helpers/platform-fixtures";
import { AgentStore } from "../../src/agents/agent-store";
import { sessionCommandsFor } from "../../src/messaging/session-command-service";
type Schedule = typeof schema.sessionSchedules.$inferSelect;
let home: string, connection: DataConnection<typeof schema>, app: Hono, sessionId: string, agentId: string, shadowId: string;
beforeEach(() => {
  home = mkdtempSync(join(tmpdir(), "luna-editor-")); setLunaHome(home); connection = new DataConnection(schema);
  const scope = fixtureScope(connection.db, "user");
  ({ agentId, shadowId } = scope);
  sessionId = new SessionStore(connection.db).createLocalSession("user:user", scope).id;
  app = new Hono();
  app.use("*", async (c, next) => { c.set("dashboardAuthSession" as never, { authenticated: true, account: { id: c.req.header("x-user") ?? "user", name: "Test", provider: "local" } } as never); c.set("lunaRequestAuthKind" as never, (c.req.header("x-runner") ? "luna-access-token" : "dashboard-cookie") as never); await next(); });
  app.route("/", createSessionCommandAdminRoutes({ db: connection.db }));
});
afterEach(() => { connection.close(); rmSync(home, { recursive: true, force: true }); });
const body = () => ({ title: "Daily reminder", targetSessionId: sessionId, action: { kind: "message.send", content: "reminder" }, nextAt: Date.now() + 3600000, timezone: "Asia/Singapore", intervalMs: 60000 });
const request = (url: string, data: unknown, method = "POST") => app.request(`${url}?agentId=${agentId}&shadowId=${shadowId}`, { method, headers: { "content-type": "application/json" }, body: JSON.stringify(data) });
async function create() { const r = await request("/schedule-editor", body()); expect(r.status).toBe(201); return await r.json() as typeof schema.sessionSchedules.$inferSelect; }
test("editor creates schedules without authority and rejects runner credentials", async () => {
  const rejected = await app.request("/schedule-editor", { method: "POST", headers: { "x-runner": "yes", "content-type": "application/json" }, body: JSON.stringify(body()) });
  expect(rejected.status).toBe(401);
  const row = await create();
  expect(row.title).toBe("Daily reminder");
  const failed = await request("/schedule-editor", { ...body(), targetSessionId: "missing" });
  expect(failed.status).toBe(404);
  expect((await request("/schedule-editor", { ...body(), nextAt: Date.now() - 1 })).status).toBe(400);
});
test("owner reads only matching schedule history and cannot send a forged execution identity", async () => {
  const row = await create();
  const foreign = fixtureScope(connection.db, "other");
  const sibling = new AgentStore(connection.db).createShadow("user", agentId, { name: "Sibling" }, "schedule-sibling");
  const siblingSession = new SessionStore(connection.db).createLocalSession("user:user", { agentId, shadowId: sibling.id });
  expect((await app.request("/schedules")).status).toBe(400);
  expect((await app.request(`/schedules?agentId=${foreign.agentId}`)).status).toBe(403);
  expect((await app.request("/commands")).status).toBe(403);
  expect(await (await app.request(`/schedules?agentId=${agentId}&shadowId=${sibling.id}`)).json()).toEqual([]);
  expect((await request("/schedule-editor", { ...body(), targetSessionId: siblingSession.id })).status).toBe(404);
  expect((await request("/schedule-editor", { ...body(), actorUserId: "other" })).status).toBe(400);
  expect((await app.request(`/schedules/${row.id}/state?agentId=${agentId}&shadowId=${sibling.id}`, {
    method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ enabled: false, revision: 1 }),
  })).status).toBe(404);
  connection.db.update(schema.sessionSchedules).set({ nextAt: Date.now() - 1 }).where(eq(schema.sessionSchedules.id, row.id)).run();
  sessionCommandsFor(connection.db, () => undefined).materializeSchedules();
  expect(await (await app.request(`/occurrences?agentId=${agentId}&shadowId=${sibling.id}`)).json()).toEqual([]);
  expect(await (await app.request(`/occurrences?agentId=${agentId}&shadowId=${shadowId}`)).json()).toMatchObject([{ scheduleId: row.id }]);
});

test("pause cancels pending occurrence; edit preserves pause and resume skips elapsed intervals", async () => {
  const row = await create();
  const commands = sessionCommandsFor(connection.db, () => undefined);
  connection.db.update(schema.sessionSchedules).set({ nextAt: Date.now() - 1 }).where(eq(schema.sessionSchedules.id, row.id)).run();
  commands.materializeSchedules();
  const occurrence = connection.db.select().from(schema.scheduleOccurrences).get()!;
  const paused = await request(`/schedules/${row.id}/state`, { enabled: false, revision: 1 });
  expect(paused.status).toBe(200); expect(((await paused.json()) as Schedule).paused).toBe(true);
  expect(commands.get(occurrence.commandId!)?.status).toBe("cancelled");
  const edited = await request(`/schedule-editor/${row.id}`, { ...body(), title: "Changed", revision: 2 }, "PUT");
  expect(connection.db.select().from(schema.scheduleOccurrences).where(eq(schema.scheduleOccurrences.id, occurrence.id)).get()?.snapshot).toEqual(occurrence.snapshot);
  expect(edited.status).toBe(200); const saved = await edited.json() as Schedule; expect(saved.enabled).toBe(false); expect(saved.revision).toBe(3);
  const past = Date.now() - 180000;
  connection.db.update(schema.sessionSchedules).set({ nextAt: past }).where(eq(schema.sessionSchedules.id, row.id)).run();
  const resume = await request(`/schedules/${row.id}/state`, { enabled: true, revision: 3 });
  expect(resume.status).toBe(200); const resumed = await resume.json() as Schedule; expect(resumed.nextAt).toBeGreaterThan(Date.now()); expect((resumed.nextAt - past) % 60000).toBe(0); expect(resumed.paused).toBe(false);
  expect((await request(`/schedules/${row.id}/state`, { enabled: false, revision: 3 })).status).toBe(409);
  expect((await request(`/schedule-editor/${row.id}`, { ...body(), revision: 3 }, "PUT")).status).toBe(409);
});
test("finished one-shot and elapsed paused one-shot cannot be replayed by resume", async () => {
  const r = await request("/schedule-editor", { ...body(), intervalMs: null }); const row = await r.json() as Schedule;
  connection.db.update(schema.sessionSchedules).set({ nextAt: Date.now() - 1 }).where(eq(schema.sessionSchedules.id, row.id)).run();
  sessionCommandsFor(connection.db, () => undefined).materializeSchedules();
  expect((await request(`/schedules/${row.id}/state`, { enabled: true, revision: 1 })).status).toBe(409);
  const edited = await request(`/schedule-editor/${row.id}`, { ...body(), intervalMs: null, revision: 1 }, "PUT");
  expect(edited.status).toBe(200);
  connection.db.update(schema.sessionSchedules).set({ nextAt: Date.now() - 1 }).where(eq(schema.sessionSchedules.id, row.id)).run();
  expect((await request(`/schedules/${row.id}/state`, { enabled: true, revision: 2 })).status).toBe(409);
});
test("resume rechecks active actor and editor validates artifact availability", async () => {
  const row = await create();
  await request(`/schedules/${row.id}/state`, { enabled: false, revision: 1 });
  connection.db.update(schema.users).set({ status: "blocked" }).where(eq(schema.users.id,"user:user")).run();
  expect((await request(`/schedules/${row.id}/state`, { enabled: true, revision: 2 })).status).toBe(403);
  connection.db.update(schema.users).set({status:"active"}).where(eq(schema.users.id,"user:user")).run();
  expect((await request("/schedule-editor", { ...body(), action: { kind: "message.send", content: "artifact:missing" } })).status).toBe(403);
  const edited = await request(`/schedule-editor/${row.id}`, { ...body(), revision: 2, action: { kind: "session.invoke", content: "analyze" } }, "PUT");
  expect(edited.status).toBe(200);
  const saved = await edited.json() as Schedule;
});
test("calendar editor computes the next run; dispatch advances and resume uses calendar rules", async () => {
  const recurrence = { kind: "weekdays" as const, time: "09:00", days: [] };
  const response = await request("/schedule-editor", { ...body(), intervalMs: null, recurrence });
  expect(response.status).toBe(201);
  const row = await response.json() as Schedule;
  expect(row.recurrence).toEqual(recurrence);
  expect(row.nextAt).toBeGreaterThan(Date.now());
  const service = sessionCommandsFor(connection.db, () => undefined);
  service.materializeSchedules(row.nextAt);
  const advanced = connection.db.select().from(schema.sessionSchedules).where(eq(schema.sessionSchedules.id, row.id)).get()!;
  expect(advanced.enabled).toBe(true);
  expect(advanced.nextAt).toBeGreaterThan(row.nextAt);
  expect(connection.db.select().from(schema.scheduleOccurrences).all()).toHaveLength(1);
  await request(`/schedules/${row.id}/state`, { enabled: false, revision: 1 });
  connection.db.update(schema.sessionSchedules).set({ nextAt: Date.now() - 604800000 }).where(eq(schema.sessionSchedules.id, row.id)).run();
  const resumed = await request(`/schedules/${row.id}/state`, { enabled: true, revision: 2 });
  expect(resumed.status).toBe(200);
  expect(((await resumed.json()) as Schedule).nextAt).toBeGreaterThan(Date.now());
  expect((await request("/schedule-editor", { ...body(), intervalMs: null, recurrence: { kind: "custom", time: "09:00", days: [] } })).status).toBe(400);
  expect((await request("/schedule-editor", { ...body(), recurrence })).status).toBe(400);
  expect((await request("/schedule-editor", { ...body(), intervalMs: null, recurrence: { ...recurrence, time: "25:00" } })).status).toBe(400);
});
test("custom frequency persists and validates every, start date and month-day combinations", async () => {
  const recurrence = { kind: "custom", time: "09:00", days: [], frequency: "monthly", every: 2, startDate: "2026-01-01", dayOfMonth: 31 };
  const created = await request("/schedule-editor", {...body(), intervalMs: null, recurrence});
  expect(created.status).toBe(201);
  const saved = await created.json() as Schedule;
  expect(saved.recurrence?.frequency).toBe("monthly");
  expect(saved.recurrence?.every).toBe(2);
  const service = sessionCommandsFor(connection.db, () => undefined);
  service.materializeSchedules(saved.nextAt);
  const advanced = connection.db.select().from(schema.sessionSchedules).where(eq(schema.sessionSchedules.id, saved.id)).get()!;
  expect(advanced.enabled).toBe(true); expect(advanced.nextAt).toBeGreaterThan(saved.nextAt);
  const invalids = [{...recurrence, every: 0}, {...recurrence, every: 1.5}, {...recurrence, startDate: "2026-02-30"}, {...recurrence, frequency: "yearly", month: 2, dayOfMonth: 30}];
  for (const invalid of invalids) expect((await request("/schedule-editor", {...body(), intervalMs: null, recurrence: invalid})).status).toBe(400);
  const yearly = await request("/schedule-editor", {...body(), intervalMs: null, recurrence: {...recurrence, frequency: "yearly", every: 2, month: 2, dayOfMonth: 29}});
  expect(yearly.status).toBe(201);
  const future = await yearly.json() as Schedule;
  expect(future.nextAt).toBeGreaterThan(Date.now());
});
test("monthly dates normalize and survive editor round trip; empty or invalid dates fail", async () => {
  const recurrence = { kind: "custom", time: "09:00", days: [], frequency: "monthly", every: 1, startDate: "2026-01-01", monthDays: [3,1,2,2] };
  const response = await request("/schedule-editor", {...body(), intervalMs: null, recurrence});
  expect(response.status).toBe(201);
  const saved = await response.json() as Schedule;
  expect(saved.recurrence?.monthDays).toEqual([1,2,3]);
  const service = sessionCommandsFor(connection.db, () => undefined);
  service.materializeSchedules(saved.nextAt);
  const next = connection.db.select().from(schema.sessionSchedules).where(eq(schema.sessionSchedules.id, saved.id)).get()!;
  expect(next.nextAt).toBeGreaterThan(saved.nextAt);
  expect(next.recurrence?.monthDays).toEqual([1,2,3]);
  for (const monthDays of [[], [0], [32], [1.5]]) expect((await request("/schedule-editor", {...body(), intervalMs: null, recurrence: {...recurrence, monthDays}})).status).toBe(400);
});
test("yearly dates round trip and validate against the chosen month; weekly supports multiple weekdays", async () => {
  const recurrence = {kind: "custom", time: "09:00", days: [], frequency: "yearly", every: 1, startDate: "2026-01-01", month: 2, monthDays: [29,1,1,28]};
  const response = await request("/schedule-editor", {...body(), intervalMs: null, recurrence});
  expect(response.status).toBe(201);
  const saved = await response.json() as Schedule;
  expect(saved.recurrence?.monthDays).toEqual([1,28,29]);
  for (const monthDays of [[], [30], [1,30]]) expect((await request("/schedule-editor", {...body(), intervalMs: null, recurrence: {...recurrence, monthDays}})).status).toBe(400);
  const weekly = await request("/schedule-editor", {...body(), intervalMs: null, recurrence: {kind: "weekly", time: "09:00", days: [1,3,5]}});
  expect(weekly.status).toBe(201);
  expect((await weekly.json() as Schedule).recurrence?.days).toEqual([1,3,5]);
});
