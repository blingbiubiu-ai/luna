test("WorkerGateway serves install.sh, release manifest, and luna-worker.js bundle with matching sha256", async () => {
  const bundlePath = join(home, "fake-luna-worker.js");
  const bundleContent = "console.log('luna-worker-test-v1');\n";
  writeFileSync(bundlePath, bundleContent);
  const expectedSha = createHash("sha256").update(bundleContent).digest("hex");
  process.env.LUNA_WORKER_BUNDLE_PATH = bundlePath;

  const runtimeDb = openExecutionDatabase(":memory:");
  try {
    const config = RuntimeConfig.parse({
      runtimeId: "runtime", serviceId: "service", environmentId: "environment",
      dataRoot: home, homeWorkerId: "local",
      serviceToken: "s".repeat(43), adminToken: "a".repeat(43),
    });
    const scheduler = new RuntimeScheduler(runtimeDb, config, new TokenAuthority(runtimeDb));
    const gateway = new WorkerGateway(runtimeDb, scheduler);

    const scriptRes = await gateway.http(new Request("http://localhost/api/worker/install.sh"));
    expect(scriptRes.status).toBe(200);
    expect(await scriptRes.text()).toContain("Luna Worker 一键部署脚本");

    const manifestRes = await gateway.http(new Request("http://localhost/api/worker/release/manifest.json"));
    expect(manifestRes.status).toBe(200);
    const manifest = await manifestRes.json() as {
      worker: { available: boolean; version: string; sha256: string; size: number; downloadPath: string };
      images: { general: { image: string }; developer: { image: string } };
    };
    expect(manifest.worker.available).toBe(true);
    expect(manifest.worker.sha256).toBe(expectedSha);
    expect(manifest.worker.version).toBe(expectedSha.slice(0, 12));
    expect(manifest.images.general.image).toContain("luna-runner");
    expect(manifest.images.developer.image).toContain("luna-runner-developer");

    const jsRes = await gateway.http(new Request("http://localhost/api/worker/release/luna-worker.js"));
    expect(jsRes.status).toBe(200);
    expect(jsRes.headers.get("x-luna-worker-sha256")).toBe(expectedSha);
    expect(await jsRes.text()).toBe(bundleContent);
  } finally {
    runtimeDb.close();
  }
});

test("WorkerUpgradeManager upgrades image and managed worker binary with symlink swap and restart", async () => {
  const workerHome = join(home, "worker");
  const binDir = join(workerHome, "bin");
  const oldReleaseDir = join(binDir, "releases", "oldversion01");
  mkdirSync(oldReleaseDir, { recursive: true });
  const oldScript = join(oldReleaseDir, "luna-worker.js");
  writeFileSync(oldScript, "console.log('old');\n");
  symlinkSync("releases/oldversion01", join(binDir, "current"));

  const oldDigest = `sha256:${"a".repeat(64)}`;
  const newDigest = `sha256:${"b".repeat(64)}`;
  const configFile = join(workerHome, "worker.json");
  writePrivateJson(configFile, {
    dataRoot: workerHome,
    imageDigest: oldDigest,
    imageRef: "hub.byted.org/wukong_devbox/luna-runner:latest",
    imageVariant: "general",
  });

  const newBundle = Buffer.from("console.log('new-worker-release');\n");
  const newSha = createHash("sha256").update(newBundle).digest("hex");
  const newVersion = newSha.slice(0, 12);

  const server = Bun.serve({
    hostname: "127.0.0.1",
    port: 0,
    fetch(request) {
      const path = new URL(request.url).pathname;
      if (path === "/api/worker/release/manifest.json") {
        return Response.json({
          worker: { available: true, version: newVersion, sha256: newSha, size: newBundle.byteLength, downloadPath: "/api/worker/release/luna-worker.js" },
          images: { general: { variant: "general", label: "General", image: "hub.byted.org/wukong_devbox/luna-runner:latest" } },
        });
      }
      if (path === "/api/worker/release/luna-worker.js") {
        return new Response(new Uint8Array(newBundle));
      }
      return new Response("not found", { status: 404 });
    },
  });

  try {
    const config = WorkerConfig.parse({
      workerId: "w-1",
      runtimeId: "r-1",
      dataRoot: workerHome,
      serviceUrl: server.url.origin,
      runtimeEndpoint: "http://127.0.0.1:8092",
      controlToken: "t".repeat(43),
      imageDigest: oldDigest,
      imageRef: "hub.byted.org/wukong_devbox/luna-runner:latest",
      imageVariant: "general",
    });

    const dockerCalls: string[][] = [];
    const states: string[] = [];
    let restarted = false;

    const manager = new WorkerUpgradeManager(config, {
      configFile,
      scriptPath: oldScript,
      restartDelayMs: 20,
      onStatusChange: () => states.push(manager.status.state),
      onRestart: () => { restarted = true; },
      execDocker: async args => {
        dockerCalls.push(args);
        if (args[0] === "pull") return "Pulled";
        if (args[0] === "image" && args[1] === "inspect") return `${newDigest}\n`;
        throw new Error(`unexpected docker args: ${args.join(" ")}`);
      },
    });

    expect(manager.managedBinary).toBe(true);
    const accepted = manager.startUpgrade({});
    expect(accepted.accepted).toBe(true);
    expect(() => manager.startUpgrade({})).toThrow();

    // Wait for async upgrade + restart callback
    for (let i = 0; i < 50 && !restarted; i++) {
      await Bun.sleep(20);
    }

    expect(restarted).toBe(true);
    expect(dockerCalls).toEqual([
      ["pull", "hub.byted.org/wukong_devbox/luna-runner:latest"],
      ["image", "inspect", "hub.byted.org/wukong_devbox/luna-runner:latest", "--format", "{{.Id}}"],
      ["image", "inspect", "hub.byted.org/wukong_devbox/luna-runner:latest"],
    ]);
    expect(config.imageDigest).toBe(newDigest);
    expect(JSON.parse(readFileSync(configFile, "utf8")).imageDigest).toBe(newDigest);
    expect(readlinkSync(join(binDir, "current"))).toBe(`releases/${newVersion}`);
    expect(readlinkSync(join(binDir, "previous"))).toBe("releases/oldversion01");
    expect(existsSync(join(binDir, "releases", newVersion, "luna-worker.js"))).toBe(true);
    expect(states).toContain("pulling_image");
    expect(states).toContain("downloading_worker");
    expect(states).toContain("restarting");
  } finally {
    await server.stop(true);
  }
});

test("POST /:agentId/workers/:workerId/upgrade enforces ownership and forwards upgrade RPC", async () => {
  const connection = new DataConnection(schema);
  const runtimeDb = openExecutionDatabase(":memory:");
  try {
    const aliceScope = fixtureScope(connection.db, "alice");
    const store = new AgentWorkerAccessStore(connection.db);
    const config = RuntimeConfig.parse({
      runtimeId: "runtime", serviceId: "service", environmentId: "environment",
      dataRoot: home, homeWorkerId: "local",
      serviceToken: "s".repeat(43), adminToken: "a".repeat(43),
    });
    const scheduler = new RuntimeScheduler(runtimeDb, config, new TokenAuthority(runtimeDb));
    const gateway = new WorkerGateway(runtimeDb, scheduler, undefined, (target, id) => {
      store.setOwned(target.ownerUserId, target.agentId, id, "active");
    });

    const app = (actor: string) => new Hono().use("*", async (c, next) => {
      (c as any).set("dashboardAuthSession", { authenticated: true, account: { id: actor, name: actor, provider: "test" } });
      (c as any).set("lunaRequestAuthKind", "dashboard-cookie");
      (c as any).set("lunaAuthorizationDb", connection.db);
      await next();
    }).route("/", createAgentWorkerAccessRoutes(connection.db, () => gateway));

    const issued = await app("alice").request(`/${aliceScope.agentId}/workers/binding-code`, { method: "POST" });
    const { code } = await issued.json() as { code: string };
    const bound = await gateway.http(new Request("http://localhost/api/worker/bind", {
      method: "POST", body: JSON.stringify({ code }),
    }));
    const { workerId } = await bound.json() as { workerId: string };

    // Disconnected worker returns 503
    const offlineRes = await app("alice").request(`/${aliceScope.agentId}/workers/${workerId}/upgrade`, { method: "POST" });
    expect(offlineRes.status).toBe(503);

    // Non-owner returns 403
    const bobRes = await app("bob").request(`/${aliceScope.agentId}/workers/${workerId}/upgrade`, { method: "POST" });
    expect(bobRes.status).toBe(403);

    // Attach mock connected worker channel with worker-upgrade-v1 capability
    let calledPath = "";
    const mockChannel = {
      call: async (_method: string, path: string) => {
        calledPath = path;
        return { accepted: true, status: { state: "pulling_image", updatedAt: Date.now() } };
      },
    };
    scheduler.workers.attach(workerId, mockChannel as any);
    scheduler.workers.heartbeat(workerId, {
      workerId,
      imageDigest: `sha256:${"a".repeat(64)}`,
      capacity: 4,
      occupied: 0,
      ready: true,
      capabilities: [WORKER_UPGRADE_CAPABILITY],
      projects: ["shared"],
    });
    // Mark socket connected in gateway map via private property for unit test
    (gateway as any).sockets.set(workerId, {});

    const okRes = await app("alice").request(`/${aliceScope.agentId}/workers/${workerId}/upgrade`, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({}),
    });
    expect(okRes.status).toBe(200);
    expect(calledPath).toBe("/v1/upgrade");
    const body = await okRes.json() as { ok: boolean; result: { accepted: boolean } };
    expect(body.ok).toBe(true);
    expect(body.result.accepted).toBe(true);
  } finally {
    runtimeDb.close();
    connection.close();
  }
});
