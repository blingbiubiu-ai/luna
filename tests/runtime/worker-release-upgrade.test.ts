let home: string;
const prevBundleEnv = process.env.LUNA_WORKER_BUNDLE_PATH;

beforeEach(() => {
  home = mkdtempSync(join(tmpdir(), "luna-worker-upgrade-"));
  setLunaHome(home);
});

afterEach(() => {
  if (prevBundleEnv === undefined) delete process.env.LUNA_WORKER_BUNDLE_PATH;
  else process.env.LUNA_WORKER_BUNDLE_PATH = prevBundleEnv;
  rmSync(home, { recursive: true, force: true });
});

test("extractImageRefFromInspect prefers registry-qualified RepoTag and handles missing/invalid JSON", () => {
  expect(extractImageRefFromInspect(JSON.stringify([{
    RepoTags: ["luna-runner-developer:latest", "hub.byted.org/wukong_devbox/luna-runner-developer:latest"],
  }]))).toBe("hub.byted.org/wukong_devbox/luna-runner-developer:latest");
  expect(extractImageRefFromInspect(JSON.stringify([{
    RepoTags: ["<none>:<none>", "luna-runner:latest"],
  }]))).toBe("luna-runner:latest");
  expect(extractImageRefFromInspect(JSON.stringify([{
    RepoTags: [],
    RepoDigests: ["hub.byted.org/wukong_devbox/luna-runner@sha256:abc"],
  }]))).toBe("hub.byted.org/wukong_devbox/luna-runner@sha256:abc");
  expect(extractImageRefFromInspect("not json")).toBeUndefined();
  const sha = `sha256:${"c".repeat(64)}`;
  expect(extractImageRepoDigestFromInspect(JSON.stringify([{
    RepoDigests: [`hub.byted.org/wukong_devbox/luna-runner-developer@${sha}`],
  }]))).toBe(sha);
  expect(extractImageRepoDigestFromInspect(JSON.stringify([{ RepoDigests: [] }]))).toBeUndefined();
});

